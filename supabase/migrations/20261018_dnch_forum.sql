-- DNCH Community v0.5 database migration, for a dedicated Supabase project.
-- Review in a private project before running; requires Supabase Auth.
-- NO SERVICE_ROLE KEY MAY APPEAR IN THE WEBSITE.
begin;

create table public.forum_categories (
 id smallint generated by default as identity primary key,
 slug text not null unique check (slug ~ '^[a-z0-9-]{3,40}$'),
 title_en text not null, title_bg text not null,
 description_en text not null, description_bg text not null,
 sort_order smallint not null default 0,
 is_active boolean not null default true
);
create table public.forum_profiles (
 id uuid primary key references auth.users(id) on delete cascade,
 display_name text not null unique check (char_length(display_name) between 3 and 40),
 created_at timestamptz not null default now()
);
create table public.forum_threads (
 id uuid primary key default gen_random_uuid(),
 category_id smallint not null references public.forum_categories(id),
 author_id uuid not null references public.forum_profiles(id),
 title text not null check (char_length(btrim(title)) between 8 and 160),
 body text not null check (char_length(btrim(body)) between 20 and 5000),
 language text not null default 'en' check (language in ('en','bg','other')),
 is_hidden boolean not null default false,
 is_locked boolean not null default false,
 created_at timestamptz not null default now()
);
create table public.forum_replies (
 id uuid primary key default gen_random_uuid(),
 thread_id uuid not null references public.forum_threads(id) on delete cascade,
 author_id uuid not null references public.forum_profiles(id),
 body text not null check (char_length(btrim(body)) between 2 and 3000),
 is_hidden boolean not null default false,
 created_at timestamptz not null default now()
);
create table public.forum_reports (
 id uuid primary key default gen_random_uuid(),
 reporter_id uuid not null references public.forum_profiles(id),
 thread_id uuid references public.forum_threads(id) on delete cascade,
 reply_id uuid references public.forum_replies(id) on delete cascade,
 reason text not null check (char_length(btrim(reason)) between 10 and 500),
 created_at timestamptz not null default now(),
 constraint exactly_one_target check ((thread_id is not null) <> (reply_id is not null))
);
create unique index one_report_per_thread on public.forum_reports(reporter_id,thread_id) where thread_id is not null;
create unique index one_report_per_reply on public.forum_reports(reporter_id,reply_id) where reply_id is not null;
create index forum_threads_recent on public.forum_threads (created_at desc) where is_hidden = false;
create index forum_threads_category_recent on public.forum_threads (category_id,created_at desc) where is_hidden = false;
create index forum_replies_thread_recent on public.forum_replies (thread_id,created_at asc) where is_hidden = false;
create index forum_threads_author on public.forum_threads(author_id,created_at desc);
create index forum_replies_author on public.forum_replies(author_id,created_at desc);
create index forum_reports_date on public.forum_reports(created_at desc);

-- Anonymous visitor sees only public forum content, not email addresses.
alter table public.forum_categories enable row level security;
alter table public.forum_profiles enable row level security;
alter table public.forum_threads enable row level security;
alter table public.forum_replies enable row level security;
alter table public.forum_reports enable row level security;
revoke all on public.forum_categories,public.forum_profiles,public.forum_threads,public.forum_replies,public.forum_reports from anon,authenticated;
grant select on public.forum_categories,public.forum_profiles to anon,authenticated;
grant select on public.forum_threads,public.forum_replies to anon,authenticated;
grant insert on public.forum_threads,public.forum_replies,public.forum_reports to authenticated;
grant usage on sequence public.forum_categories_id_seq to postgres,service_role;

create policy "public categories" on public.forum_categories for select to anon,authenticated using(is_active);
create policy "public pseudonyms" on public.forum_profiles for select to anon,authenticated using(true);
create policy "public visible topics" on public.forum_threads for select to anon,authenticated using(not is_hidden);
create policy "members create own topics" on public.forum_threads for insert to authenticated
with check ((select auth.uid()) = author_id and is_hidden=false and is_locked=false);
create policy "public visible replies" on public.forum_replies for select to anon,authenticated
using(not is_hidden and exists(select 1 from public.forum_threads t where t.id=thread_id and not t.is_hidden));
create policy "members reply to open topics" on public.forum_replies for insert to authenticated
with check ((select auth.uid())=author_id and is_hidden=false and exists(
 select 1 from public.forum_threads t where t.id=thread_id and not t.is_hidden and not t.is_locked));
-- Reports have no client SELECT privilege. Administrators can examine them in Supabase Studio.
create policy "members can report" on public.forum_reports for insert to authenticated
with check ((select auth.uid())=reporter_id);

-- Automatic pseudonyms: emails remain private inside the Auth schema.
create function public.forum_create_profile() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
 insert into public.forum_profiles(id,display_name)
 values (new.id, 'Member-' || substr(replace(new.id::text,'-',''),1,12));
 return new;
end; $$;
create trigger forum_user_created after insert on auth.users
for each row execute function public.forum_create_profile();

-- Light DB-level throttling, independent of buttons in the browser.
-- All user-set creation timestamps and visibility flags are overridden here.
create function public.forum_guard_thread() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
 if new.author_id is distinct from auth.uid() then raise exception 'Invalid topic owner'; end if;
 if exists (select 1 from public.forum_threads where author_id=new.author_id and created_at>now()-interval '60 seconds')
 then raise exception 'Wait a minute before creating another topic'; end if;
 new.created_at := now(); new.is_hidden := false; new.is_locked := false;
 return new;
end; $$;
create trigger forum_thread_guard before insert on public.forum_threads
for each row execute function public.forum_guard_thread();

create function public.forum_guard_reply() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
 if new.author_id is distinct from auth.uid() then raise exception 'Invalid reply owner'; end if;
 if exists (select 1 from public.forum_replies where author_id=new.author_id and created_at>now()-interval '15 seconds')
 then raise exception 'Wait before replying again'; end if;
 new.created_at := now();new.is_hidden := false;
 return new;
end; $$;
create trigger forum_reply_guard before insert on public.forum_replies
for each row execute function public.forum_guard_reply();

create function public.forum_guard_report() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
 if new.reporter_id is distinct from auth.uid() then raise exception 'Invalid reporter'; end if;
 if exists (select 1 from public.forum_reports where reporter_id=new.reporter_id and created_at>now()-interval '30 seconds')
 then raise exception 'Wait before reporting again'; end if;
 new.created_at := now();
 return new;
end; $$;
create trigger forum_report_guard before insert on public.forum_reports
for each row execute function public.forum_guard_report();

-- Prevent clients from calling internal SECURITY DEFINER trigger functions directly.
revoke execute on function public.forum_create_profile() from public,anon,authenticated;
revoke execute on function public.forum_guard_thread() from public,anon,authenticated;
revoke execute on function public.forum_guard_reply() from public,anon,authenticated;
revoke execute on function public.forum_guard_report() from public,anon,authenticated;

